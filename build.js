#!/usr/bin/env node
/* Writes config.js from environment variables. No bundler, no dependencies.
   With no FIREBASE_* vars set it writes a null config and the app stays local-only. */
'use strict';

const fs = require('fs');
const path = require('path');
const https = require('https');

const env = process.env;

/* safety caps, overridable from the host. Google allows 600 calls/min per user
   and bills only above 1,000,000/day, so these sit far below both. */
/* the OAuth client id is public — it ships in the page either way — so baking it
   in from an env var is safe, and saves pasting it on every device. */
const googleClientId = String(env.GOOGLE_CLIENT_ID || '').trim();
/* Optional API keys. Not required for OAuth calls, but if you have them they are
   sent as ?key= on their API, which attributes quota to the project. */
const googleCalApi = String(env.GOOGLE_CAL_API || '').trim();
const googleTasksApi = String(env.GOOGLE_TASKS_API || '').trim();

const limits = {
  callsPerMinute: Number(env.PLAYDAY_CALLS_PER_MINUTE) || 120,
  callsPerDay: Number(env.PLAYDAY_CALLS_PER_DAY) || 8000
};
const config = {
  apiKey: env.FIREBASE_API_KEY || '',
  authDomain: env.FIREBASE_AUTH_DOMAIN || '',
  projectId: env.FIREBASE_PROJECT_ID || '',
  storageBucket: env.FIREBASE_STORAGE_BUCKET || '',
  messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID || '',
  appId: env.FIREBASE_APP_ID || '',
  measurementId: env.FIREBASE_MEASUREMENT_ID || ''
};

const hasCore = !!(config.apiKey && config.projectId);
const limitsLine = 'window.__PLAYDAY_LIMITS = ' + JSON.stringify(limits) + ';\n' +
  'window.__GOOGLE_CLIENT_ID = ' + JSON.stringify(googleClientId) + ';\n' +
  'window.__GOOGLE_CAL_API = ' + JSON.stringify(googleCalApi) + ';\n' +
  'window.__GOOGLE_TASKS_API = ' + JSON.stringify(googleTasksApi) + ';\n';
const body = (hasCore
  ? '/* generated by build.js — do not edit */\nwindow.__FIREBASE_CONFIG = ' + JSON.stringify(config, null, 2) + ';\n'
  : '/* generated by build.js — no Firebase env vars were set, so sync is off */\nwindow.__FIREBASE_CONFIG = null;\n') + limitsLine;

/* Self-host the Firebase SDK when a config is present. Fetching it from
   gstatic at runtime fails behind ad blockers, Brave Shields, DNS filters and
   some CSP setups — vendoring it removes the third-party request entirely. */
const FB_VERSION = '11.0.2';
const SDK_FILES = ['firebase-app.js', 'firebase-auth.js', 'firebase-firestore.js'];
const vendorDir = path.join(__dirname, 'vendor');

function fetchText(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { timeout: 20000 }, res => {
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error('HTTP ' + res.statusCode + ' for ' + url));
      }
      let body = '';
      res.setEncoding('utf8');
      res.on('data', c => { body += c; });
      res.on('end', () => resolve(body));
    });
    req.on('timeout', () => req.destroy(new Error('timeout fetching ' + url)));
    req.on('error', reject);
  });
}

async function vendorSdk() {
  if (!hasCore) return false;
  fs.mkdirSync(vendorDir, { recursive: true });
  for (const name of SDK_FILES) {
    const dest = path.join(vendorDir, name);
    if (fs.existsSync(dest) && fs.statSync(dest).size > 1000) continue;  // already vendored
    const body = await fetchText('https://www.gstatic.com/firebasejs/' + FB_VERSION + '/' + name);
    if (body.indexOf('export') === -1) throw new Error(name + ' did not look like an ES module');
    fs.writeFileSync(dest, body, 'utf8');
  }
  return true;
}

const target = path.join(__dirname, 'config.js');
fs.writeFileSync(target, body, 'utf8');

if (hasCore) {
  console.log('config.js written — project ' + config.projectId + ', auth domain ' + (config.authDomain || '(unset)'));
} else {
  console.log('config.js written — no FIREBASE_* env vars found, app runs local-only');
}
console.log('call caps — ' + limits.callsPerMinute + '/min, ' + limits.callsPerDay + '/day');
console.log(googleClientId ? 'google client id — baked in from GOOGLE_CLIENT_ID' : 'google client id — not set, paste it in Settings');
console.log('api keys — calendar ' + (googleCalApi ? 'set' : 'unset') + ', tasks ' + (googleTasksApi ? 'set' : 'unset') + ' (neither is required)');

/* vendor the SDK, but never fail the build over it: the app falls back to the CDN */
(async () => {
  if (!hasCore) return;
  try {
    const ok = await vendorSdk();
    if (ok) {
      const flag = '/* generated by build.js */\nwindow.__FIREBASE_VENDOR = true;\n';
      fs.appendFileSync(target, flag);
      console.log('firebase sdk vendored into vendor/ — no runtime fetch from gstatic');
    }
  } catch (err) {
    console.log('could not vendor the firebase sdk (' + err.message + ') — the app will load it from the CDN instead');
  }
})();
